// Package prefixtree это параметризованное префиксное дерево для маршрутизации адресов
//
// В дерево кладутся значения по шаблонам адресов, а достаются по конкретным адресам:
//
//	/api/v1/health         статический шаблон
//	/u/:slot/api/*path     :slot это один сегмент до "/", *path это весь остаток адреса
//
// # Приоритеты
//
// На каждом уровне сначала проверяется статика, потом параметр, потом CatchAll.
// Если ветка не дошла до конца, поиск откатывается и пробует следующую.
// CatchAll может быть только один и только в конце шаблона.
//
// # Дерево и хранилище
//
// [New] возвращает [Tree] со всеми операциями: Set, Delete, Replace, Get и Clone.
// Tree не потокобезопасен: изменения нельзя делать параллельно с другими вызовами.
//
// [NewStorage] возвращает [Storage] для конкурентного чтения. Изменения идут в мастер-дерево под мьютексом,
// после каждого успешного изменения копия мастера публикуется через атомик,
// а [Storage.Tree] отдаёт её как [TreeReadonly]. Читатели никогда не ждут.
//
// # Ошибки
//
// Все ошибки пакета проверяются через [Code]:
//
//	switch prefixtree.Code(err) {
//	case prefixtree.OK:
//	case prefixtree.PathNotFound:
//	default:
//	}
//
// # Стоимость
//
// Промах в Get не аллоцирует, найденное значение стоит одну аллокацию.
// Значения параметров это подстроки запрошенного адреса, ничего не копируется.
